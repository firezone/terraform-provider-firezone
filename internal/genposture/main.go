// Command genposture writes internal/provider/policy_posture_fields_gen.go:
// a table of every device posture field the Go SDK defines, with the kind
// of value each takes. The provider uses it to validate a check's operator
// and to check its value's type at plan time.
//
// It reads the SDK's own generated constants, so the table follows
// whichever SDK version go.mod pins. Run it with `go generate ./...`,
// which `mise run tfdocs` does, after bumping the SDK.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const sdkModule = "github.com/firezone/firezone-sdk-go"

// kinds maps the SDK's field types to the provider's kind names.
var kinds = map[string]string{
	"PostureBoolField":        "postureKindBool",
	"PostureStringField":      "postureKindString",
	"PostureIntegerField":     "postureKindInteger",
	"PostureFloatField":       "postureKindFloat",
	"PostureVersionField":     "postureKindVersion",
	"PostureTimestampField":   "postureKindTimestamp",
	"PostureIPField":          "postureKindIP",
	"PostureJSONField":        "postureKindJSON",
	"PostureStringArrayField": "postureKindStringArray",
}

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", sdkModule).Output()
	if err != nil {
		log.Fatalf("locating %s: %v", sdkModule, err)
	}
	src := filepath.Join(strings.TrimSpace(string(out)), "posture_fields_gen.go")

	file, err := parser.ParseFile(token.NewFileSet(), src, nil, 0)
	if err != nil {
		log.Fatal(err)
	}

	fields := map[string]string{}
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.CONST {
			continue
		}
		for _, spec := range gen.Specs {
			vs := spec.(*ast.ValueSpec)
			typ, ok := vs.Type.(*ast.Ident)
			if !ok || len(vs.Values) != 1 {
				continue
			}
			kind, ok := kinds[typ.Name]
			if !ok {
				log.Fatalf("unknown SDK field type %s; teach genposture about it", typ.Name)
			}
			name, err := strconv.Unquote(vs.Values[0].(*ast.BasicLit).Value)
			if err != nil {
				log.Fatal(err)
			}
			fields[name] = kind
		}
	}
	if len(fields) == 0 {
		log.Fatalf("no fields found in %s", src)
	}

	names := make([]string, 0, len(fields))
	for name := range fields {
		names = append(names, name)
	}
	sort.Strings(names)

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by internal/genposture from %s; DO NOT EDIT.\n\n", sdkModule)
	buf.WriteString("package provider\n\n")
	buf.WriteString("// postureFieldKinds is every device posture field the SDK knows.\n")
	buf.WriteString("var postureFieldKinds = map[string]postureKind{\n")
	for _, name := range names {
		fmt.Fprintf(&buf, "\t%q: %s,\n", name, fields[name])
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join("internal", "provider", "policy_posture_fields_gen.go"), formatted, 0o600); err != nil {
		log.Fatal(err)
	}
}
